const RCON: [u8; 10] = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36];

#[derive(Clone, Copy)]
pub struct Aes {
    rounds: usize,
    rk: [[u8; 16]; 15],
}

fn sbox(b: u8) -> u8 {
    SBOX.get(usize::from(b)).copied().unwrap_or(0)
}

fn inv_sbox(b: u8) -> u8 {
    INV_SBOX.get(usize::from(b)).copied().unwrap_or(0)
}

fn sub_word(w: [u8; 4]) -> [u8; 4] {
    [sbox(w[0]), sbox(w[1]), sbox(w[2]), sbox(w[3])]
}

fn rot_word(w: [u8; 4]) -> [u8; 4] {
    [w[1], w[2], w[3], w[0]]
}

fn xor4(a: [u8; 4], b: [u8; 4]) -> [u8; 4] {
    [a[0] ^ b[0], a[1] ^ b[1], a[2] ^ b[2], a[3] ^ b[3]]
}

fn xtime(x: u8) -> u8 {
    (x << 1) ^ if x & 0x80 != 0 { 0x1b } else { 0 }
}

fn gmul(mut a: u8, mut b: u8) -> u8 {
    let mut p = 0u8;
    for _ in 0..8 {
        if b & 1 != 0 {
            p ^= a;
        }
        a = xtime(a);
        b >>= 1;
    }
    p
}

impl Aes {
    pub fn new(key: &[u8]) -> Option<Self> {
        let (nk, rounds) = match key.len() {
            16 => (4usize, 10usize),
            24 => (6usize, 12usize),
            32 => (8usize, 14usize),
            _ => return None,
        };
        let total_words = 4 * (rounds + 1);
        let mut w = [[0u8; 4]; 60];
        for (i, slot) in w.iter_mut().take(nk).enumerate() {
            let chunk = key.get(i * 4..i * 4 + 4)?;
            *slot = chunk.try_into().ok()?;
        }
        for i in nk..total_words {
            let mut temp = *w.get(i - 1)?;
            if i % nk == 0 {
                let rcon = *RCON.get(i / nk - 1)?;
                temp = sub_word(rot_word(temp));
                temp[0] ^= rcon;
            } else if nk == 8 && i % nk == 4 {
                temp = sub_word(temp);
            }
            let prev = *w.get(i - nk)?;
            if let Some(slot) = w.get_mut(i) {
                *slot = xor4(prev, temp);
            }
        }
        let mut rk = [[0u8; 16]; 15];
        for (r, round_key) in rk.iter_mut().take(rounds + 1).enumerate() {
            for c in 0..4 {
                let word = *w.get(r * 4 + c)?;
                if let Some(dst) = round_key.get_mut(c * 4..c * 4 + 4) {
                    dst.copy_from_slice(&word);
                }
            }
        }
        Some(Self { rounds, rk })
    }

    pub fn encrypt_block(&self, s: &mut [u8; 16]) {
        if let Some(rk0) = self.rk.first() {
            add_round_key(s, rk0);
        }
        for r in 1..self.rounds {
            for b in s.iter_mut() {
                *b = sbox(*b);
            }
            shift_rows(s);
            mix_columns(s);
            if let Some(rk) = self.rk.get(r) {
                add_round_key(s, rk);
            }
        }
        for b in s.iter_mut() {
            *b = sbox(*b);
        }
        shift_rows(s);
        if let Some(rkn) = self.rk.get(self.rounds) {
            add_round_key(s, rkn);
        }
    }

    pub fn decrypt_block(&self, s: &mut [u8; 16]) {
        if let Some(rkn) = self.rk.get(self.rounds) {
            add_round_key(s, rkn);
        }
        for r in (1..self.rounds).rev() {
            inv_shift_rows(s);
            for b in s.iter_mut() {
                *b = inv_sbox(*b);
            }
            if let Some(rk) = self.rk.get(r) {
                add_round_key(s, rk);
            }
            inv_mix_columns(s);
        }
        inv_shift_rows(s);
        for b in s.iter_mut() {
            *b = inv_sbox(*b);
        }
        if let Some(rk0) = self.rk.first() {
            add_round_key(s, rk0);
        }
    }
}

fn add_round_key(s: &mut [u8; 16], rk: &[u8; 16]) {
    for (a, b) in s.iter_mut().zip(rk) {
        *a ^= *b;
    }
}

fn shift_rows(s: &mut [u8; 16]) {
    let t = *s;
    s[1] = t[5];
    s[5] = t[9];
    s[9] = t[13];
    s[13] = t[1];

    s[2] = t[10];
    s[6] = t[14];
    s[10] = t[2];
    s[14] = t[6];

    s[3] = t[15];
    s[7] = t[3];
    s[11] = t[7];
    s[15] = t[11];
}

fn inv_shift_rows(s: &mut [u8; 16]) {
    let t = *s;
    s[1] = t[13];
    s[5] = t[1];
    s[9] = t[5];
    s[13] = t[9];

    s[2] = t[10];
    s[6] = t[14];
    s[10] = t[2];
    s[14] = t[6];

    s[3] = t[7];
    s[7] = t[11];
    s[11] = t[15];
    s[15] = t[3];
}

fn mix_columns(s: &mut [u8; 16]) {
    for col in s.as_chunks_mut::<4>().0 {
        let [s0, s1, s2, s3] = *col;
        let t = s0 ^ s1 ^ s2 ^ s3;
        *col = [
            s0 ^ t ^ xtime(s0 ^ s1),
            s1 ^ t ^ xtime(s1 ^ s2),
            s2 ^ t ^ xtime(s2 ^ s3),
            s3 ^ t ^ xtime(s3 ^ s0),
        ];
    }
}

fn inv_mix_columns(s: &mut [u8; 16]) {
    for col in s.as_chunks_mut::<4>().0 {
        let [a, b, c, d] = *col;
        *col = [
            gmul(a, 0x0e) ^ gmul(b, 0x0b) ^ gmul(c, 0x0d) ^ gmul(d, 0x09),
            gmul(a, 0x09) ^ gmul(b, 0x0e) ^ gmul(c, 0x0b) ^ gmul(d, 0x0d),
            gmul(a, 0x0d) ^ gmul(b, 0x09) ^ gmul(c, 0x0e) ^ gmul(d, 0x0b),
            gmul(a, 0x0b) ^ gmul(b, 0x0d) ^ gmul(c, 0x09) ^ gmul(d, 0x0e),
        ];
    }
}

/// AES-CBC decryption over all complete 16-byte blocks in `data`.
pub fn decrypt_cbc(key: &[u8], iv: &[u8; 16], data: &[u8]) -> Option<Vec<u8>> {
    let aes = Aes::new(key)?;
    let n = data.len() & !15;
    let mut out = Vec::with_capacity(n);
    let mut prev = *iv;
    for chunk in data.get(..n)?.as_chunks::<16>().0 {
        let mut block = *chunk;
        aes.decrypt_block(&mut block);
        for (b, p) in block.iter_mut().zip(prev) {
            *b ^= p;
        }
        out.extend_from_slice(&block);
        prev = *chunk;
    }
    Some(out)
}

/// WinZip AES-CTR decryption (counter starts at 1 in little-endian byte order).
pub fn decrypt_winzip_ctr(key: &[u8], data: &[u8]) -> Option<Vec<u8>> {
    let aes = Aes::new(key)?;
    let mut out = Vec::with_capacity(data.len());
    let mut counter = 1u128;
    for chunk in data.chunks(16) {
        let mut ks = counter.to_le_bytes();
        aes.encrypt_block(&mut ks);
        counter = counter.wrapping_add(1);
        for (b, k) in chunk.iter().zip(ks) {
            out.push(*b ^ k);
        }
    }
    Some(out)
}

