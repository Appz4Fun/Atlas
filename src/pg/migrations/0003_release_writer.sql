-- These tables own the native release writer's normalized view of incoming
-- overview data. The header archive remains the source of the original headers.
create table releases (
    id              bigint generated by default as identity primary key,
    group_name      text collate "C" not null,
    is_collection   boolean not null,
    identity_key    bytea not null,
    name            text collate "C" not null,
    poster          text not null,
    posted_date     text not null,
    display_name    text,
    is_obfuscated   boolean not null,
    name_source     bigint,
    size            bigint not null default 0,
    parts           bigint not null default 0,
    file_total      bigint,
    complete        boolean not null default false,
    unique (group_name, is_collection, identity_key)
);

create table files (
    id              bigint generated by default as identity primary key,
    release_id      bigint not null references releases on delete cascade,
    filename_key    bytea not null,
    filename        text collate "C" not null,
    expected        bigint,
    file_total      bigint,
    subject         text,
    subject_part    bigint,
    subject_mid     bytea,
    zero_file_index boolean not null default false,
    distinct_parts  bigint not null default 0,
    first_part      bigint,
    last_part       bigint,
    touched_at      bigint,
    complete        boolean not null default false,
    unique (release_id, filename_key),
    unique (release_id, id)
);

-- The exact message-id is kept as bytes, including IDs too large to index.
-- A copy is a duplicate across all files of a release. The same part under a
-- different message-id still counts as an article, as in the shard writer.
create table segments (
    release_id      bigint not null,
    file_id         bigint not null,
    message_key     bytea not null,
    message_id      bytea not null,
    part            bigint,
    bytes           bigint not null,
    primary key (release_id, message_key),
    foreign key (release_id, file_id) references files(release_id, id) on delete cascade
);
create index segments_file_part on segments (file_id, part);

-- Distinct part numbers are incremental, so a late part need not rescan all
-- messages in a large file to update completeness.
create table file_parts (
    file_id bigint not null references files on delete cascade,
    part    bigint not null,
    primary key (file_id, part)
);

create table pp_queue (
    release_id  bigint primary key references releases on delete cascade,
    due_at      bigint not null,
    generation  bigint not null default 1
);
create index pp_queue_due on pp_queue (due_at, release_id);

create table release_writer_junk (
    group_name      text collate "C" not null,
    is_collection   boolean not null,
    identity_key    bytea not null,
    primary key (group_name, is_collection, identity_key)
);
