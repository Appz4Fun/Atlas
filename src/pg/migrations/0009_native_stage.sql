create function atlas_native_sidecar_bytes() returns trigger language plpgsql as $$
declare delta bigint;
begin
 delta:=case when TG_OP='DELETE' then 0 else coalesce(octet_length(NEW.text),0) end
       -case when TG_OP='INSERT' then 0 else coalesce(octet_length(OLD.text),0) end;
 update meta set value=greatest(0,coalesce(value,0)+delta) where key='sidecar_text_bytes';
 return null;
end $$;
create trigger native_sidecar_bytes after insert or update or delete on sidecars
 for each row execute function atlas_native_sidecar_bytes();
create function atlas_native_archive_names_delete() returns trigger language plpgsql as $$
begin
 update meta set value=greatest(0,coalesce(value,0)-(select coalesce(sum(octet_length(name)+32),0)
   from archive_inner_files where release_id=OLD.id)) where key='archive_name_bytes';
 return OLD;
end $$;
create trigger native_archive_names_delete before delete on releases
 for each row execute function atlas_native_archive_names_delete();

