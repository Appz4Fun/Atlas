create function atlas_native_search_dirty() returns trigger language plpgsql as $$
declare rid bigint;
begin
 if TG_OP='UPDATE' and NEW is not distinct from OLD then return null; end if;
 if TG_TABLE_NAME='releases' then
   rid:=case when TG_OP='DELETE' then OLD.id else NEW.id end;
 else
   rid:=case when TG_OP='DELETE' then OLD.release_id else NEW.release_id end;
 end if;
 insert into word_queue(release_id) values(rid) on conflict(release_id) do update set n=word_queue.n+1;
 update native_catalog_revision set revision=revision+1 where singleton;
 return null;
end $$;
create trigger native_release_search_dirty after insert or update or delete on releases
 for each row execute function atlas_native_search_dirty();
create trigger native_category_search_dirty after insert or update or delete on release_category
 for each row execute function atlas_native_search_dirty();
create trigger native_media_search_dirty after insert or update or delete on media_release
 for each row execute function atlas_native_search_dirty();
create function atlas_native_known_as_dirty() returns trigger language plpgsql as $$
declare changed bigint;
begin
 if TG_OP='UPDATE' and NEW is not distinct from OLD then return null; end if;
 insert into word_queue(release_id) select release_id from media_release where title_key=
   case when TG_OP='DELETE' then OLD.title_key else NEW.title_key end
 on conflict(release_id) do update set n=word_queue.n+1;
 get diagnostics changed=ROW_COUNT;
 if changed>0 then update native_catalog_revision set revision=revision+1 where singleton; end if;
 return null;
end $$;
create trigger native_known_as_dirty after insert or update or delete on ext_media_titles
 for each row execute function atlas_native_known_as_dirty();

create function atlas_native_queue_new_intent() returns trigger language plpgsql as $$
begin
 if NEW.generation<>OLD.generation or NEW.work_serial<>OLD.work_serial then
   NEW.logical_operation_id:=null;
 end if;
 return NEW;
end $$;
create trigger native_queue_new_intent before update on pp_queue
 for each row execute function atlas_native_queue_new_intent();

