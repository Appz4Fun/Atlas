-- Fresh native Stage schema. No legacy release/header/queue/state rows are imported.
-- Valuable natural-key cache tables remain ext_* and are restored separately.

-- This migration is intentionally for the new catalog, never an implicit
-- adoption of old releases, header manifests or historical import state.
do $$ declare relation text; occupied boolean; begin
 if not pg_try_advisory_xact_lock(hashtext('atlas.indexer'),hashtext(current_schema())) then
   raise exception 'stop the native owner before fresh Stage migration' using errcode='55000';
 end if;
 if exists(select 1 from releases) or exists(select 1 from files)
    or exists(select 1 from segments) or exists(select 1 from pp_queue)
    or exists(select 1 from header_blocks) or exists(select 1 from history_imports) then
   raise exception 'native Stage requires a fresh catalog; restore valuable caches separately' using errcode='55000';
 end if;
 foreach relation in array array['groups','meta','backfill_chunks','backfill_deepest','backfill_media',
   'backfill_speculative','backfill_sweep_gen','backfill_sweeps','backfill_wanted','spot_comments',
   'spot_disposals','spot_reports','spots_seen','inferred_asked','inferred_ids','repair_tried','repair_older'] loop
   if relation='meta' then
     -- Migration 1's untouched allocator seed is not indexed/worker state.
     -- DISTINCT checks reject NULL, nondefault values and stale text too.
     select exists(select 1 from meta where key is distinct from 'next_seq'
       or value is distinct from 1 or text_value is not null) into occupied;
   else
     execute format('select exists(select 1 from %I)',relation) into occupied;
   end if;
   if occupied then
     raise exception 'native Stage requires fresh cursor and worker tables' using errcode='55000';
   end if;
 end loop;
end $$;

