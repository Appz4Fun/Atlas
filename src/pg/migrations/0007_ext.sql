-- What came from an external service and can't be fetched again at will: PreDB titles and feed state, the media
-- providers' answers, OpenSubtitles' answers, the PreDB pages as fetched, the HTTP cache (its pinned PreDB
-- snapshots), and releases thawed by hand. Every table here is named `ext_*`, so the nightly dump takes exactly
-- these (`pg::ext`), and nothing prunes them: what the SQLite raw store capped stays here for good.
--
-- Columns are SQLite's, one for one (INTEGER as bigint, TEXT as text, BLOB as bytea), so the move copies rows as
-- they are and checks each table by an order-free digest of its rows.

create table ext_predb_titles (
    -- numbered by Postgres for new rows, as SQLite's INTEGER PRIMARY KEY did (moved rows keep theirs; `pg::ext`
    -- sets each counter past the highest after a move or restore)
    id          bigint generated by default as identity primary key,
    title       text not null,
    source      bigint not null,
    category    text,
    size_bytes  bigint,
    files       bigint,
    pre_at      bigint,
    nuked       bigint not null default 0,
    nuke_reason text,
    added_at    bigint not null
);
create index ext_predb_titles_pre_at on ext_predb_titles (pre_at);

create table ext_predb_feeds (
    source       bigint primary key,
    key          text not null,
    next_poll_at bigint not null default 0,
    failures     bigint not null default 0,
    resume_page  bigint not null default 0,
    gap_floor    bigint not null default 0,
    history_page bigint not null default 0,
    history_read bigint not null default 0,
    last_ok_at   bigint,
    last_error   text,
    inserted     bigint not null default 0,
    updated      bigint not null default 0,
    last_rows    bigint
);

create table ext_predb_meta (
    key   text collate "C" primary key,
    value bigint
);

create table ext_media_titles (
    title_key    bigint primary key,
    kind         bigint not null,
    title        text not null,
    year         bigint,
    state        bigint not null,
    checked_mask bigint not null,
    tvdb_id      bigint,
    tvmaze_id    bigint,
    trakt_id     bigint,
    tmdb_id      bigint,
    imdb_id      bigint,
    tvrage_id    bigint,
    found_title  text,
    checked_at   bigint not null,
    next_check   bigint,
    misses       bigint not null default 0,
    fanout_done  bigint not null default 1
);
create index ext_media_titles_fanout on ext_media_titles (title_key) where fanout_done = 0;

create table ext_media_details (
    kind        bigint not null,
    tmdb_id     bigint not null,
    title       text,
    overview    text,
    genres      text,
    runtime     bigint,
    status      text,
    network     text,
    cast_names  text,
    released    text,
    bluray      text,
    poster      text,
    tmdb_score  bigint,
    imdb_score  bigint,
    rotten      bigint,
    metacritic  bigint,
    trakt_score bigint,
    fetched_at  bigint not null,
    backdrop    text,
    primary key (kind, tmdb_id)
);

create table ext_media_details_lookups (
    lookup     text collate "C" primary key,
    tmdb_id    bigint,
    checked_at bigint not null
);

create table ext_opensubtitles (
    moviehash    text collate "C" primary key,
    imdb_id      bigint,
    tmdb_id      bigint,
    kind         text,
    title        text,
    year         bigint,
    season       bigint,
    episode      bigint,
    release_name text,
    raw_json_zst bytea,
    checked_at   bigint not null
);
alter table ext_opensubtitles alter column raw_json_zst set storage external;

create table ext_predb_pages (
    id          bigint generated by default as identity primary key,
    source_id   bigint not null,
    source_key  text not null,
    url         text not null,
    page        bigint not null default 1,
    body_sha256 bytea not null,
    body_zst    bytea not null,
    fetched_at  bigint not null,
    unique (source_id, body_sha256)
);
-- already zstd: TOAST mustn't try to compress it again
alter table ext_predb_pages alter column body_zst set storage external;

create table ext_predb_page_events (
    seq        bigint generated by default as identity primary key,
    log_id     bigint not null,
    page       bigint not null default 1,
    fetched_at bigint not null
);
create index ext_predb_page_events_log_id on ext_predb_page_events (log_id);

create table ext_http_cache (
    cache_key  text collate "C" primary key,
    source     text not null,
    url        text not null,
    status     bigint not null,
    body_zst   bytea not null,
    fetched_at bigint not null
);
alter table ext_http_cache alter column body_zst set storage external;
create index ext_http_cache_fetched_at on ext_http_cache (fetched_at);

-- a release thawed by hand, by its name and group: the id it had doesn't survive indexing again
create table ext_freeze_exempt (
    name           text collate "C" not null,
    group_name     text collate "C" not null,
    at             bigint not null,
    old_release_id bigint,
    primary key (name, group_name)
);
