#!/usr/bin/env python3
"""Writes src/ptt/rules.rs from the Kodi add-on's PTT handlers.py, in its order.

    scripts/gen_ptt.py path/to/resources/lib/ptt/handlers.py > src/ptt/rules.rs

Handlers that are Python functions become `Custom` entries, written by hand in src/ptt/mod.rs.
"""
import ast
import re
import sys

FLAGS = {"IGNORECASE": "i", "DOTALL": "s", "MULTILINE": "m", "VERBOSE": "x"}


def flags_of(node):
    if node is None:
        return ""
    if isinstance(node, ast.BinOp):
        return flags_of(node.left) + flags_of(node.right)
    if isinstance(node, ast.Attribute):
        return FLAGS[node.attr]
    raise ValueError(ast.dump(node))


def to_rust_regex(pattern):
    """What Python's `re` takes literally but the `regex` crate doesn't: `[` in a class, and a `{` that repeats nothing."""
    out = []
    i = 0
    first = False
    in_class = False
    while i < len(pattern):
        c = pattern[i]
        if c == "\\":
            out.append(pattern[i : i + 2])
            i += 2
            first = False
            continue
        if in_class:
            if c == "]" and not first:
                in_class = False
            elif c == "[":
                c = "\\["
            elif c in "&~" and pattern[i + 1 : i + 2] == c:
                c = "\\" + c
            first = False
            out.append(c)
            i += 1
            continue
        if c == "[":
            in_class = True
            first = True
            out.append(c)
            i += 1
            if pattern[i : i + 1] == "^":
                out.append("^")
                i += 1
            continue
        if c == "{" and not re.match(r"\{\d*,?\d*\}", pattern[i:]):
            c = "\\{"
        elif c == "}" and not re.search(r"\{\d*,?\d*$", "".join(out)):
            c = "\\}"
        out.append(c)
        i += 1
    return "".join(out)


def transformer(node):
    if node is None:
        return "T::None"
    src = ast.unparse(node)
    simple = {
        "none": "T::None",
        "boolean": "T::Boolean",
        "integer": "T::Integer",
        "first_integer": "T::FirstInteger",
        "lowercase": "T::Lowercase",
        "uppercase": "T::Uppercase",
        "range_func": "T::Range",
        "range_x_of_y_func": "T::RangeXOfY",
        "transform_resolution": "T::Resolution",
        "array(integer)": "T::ArrayInteger",
    }
    if src in simple:
        return simple[src]
    if isinstance(node, ast.Call):
        name = node.func.id
        arg = node.args[0]
        if name == "value":
            return f"T::Value({rust_str(ast.literal_eval(arg))})"
        if name == "date":
            formats = ast.literal_eval(arg)
            formats = [formats] if isinstance(formats, str) else formats
            return "T::Date(&[" + ", ".join(rust_str(f) for f in formats) + "])"
        if name == "uniq_concat":
            inner = arg
            if isinstance(inner, ast.Call) and inner.func.id == "value":
                return f"T::UniqValue({rust_str(ast.literal_eval(inner.args[0]))})"
            raise ValueError(src)
    raise ValueError(src)


def rust_str(s):
    return "r" + "#" * 4 + '"' + s + '"' + "#" * 4


def main():
    tree = ast.parse(open(sys.argv[1]).read())
    body = next(n for n in tree.body if isinstance(n, ast.FunctionDef) and n.name == "add_defaults").body
    print("// Generated by scripts/gen_ptt.py from PTT's handlers.py. Don't edit by hand.")
    print("use super::{Entry, Rule, T};\n")
    print("pub const RULES: &[Entry] = &[")
    for stmt in body:
        if not (isinstance(stmt, ast.Expr) and isinstance(stmt.value, ast.Call)):
            continue
        call = stmt.value
        if not (isinstance(call.func, ast.Attribute) and call.func.attr == "add_handler"):
            continue
        args = call.args
        if len(args) >= 2 and isinstance(args[1], ast.Name):
            print(f'    Entry::Custom("{args[1].id}"),')
            continue
        name = ast.literal_eval(args[0])
        compile_call = args[1]
        pattern = ast.literal_eval(compile_call.args[0])
        flags = flags_of(compile_call.args[1] if len(compile_call.args) > 1 else None)
        options = ast.literal_eval(args[3]) if len(args) > 3 else {}
        assert "value" not in options
        prefix = f"(?{flags})" if flags else ""
        print(
            "    Entry::Rule(Rule {"
            f' name: "{name}",'
            f" pattern: {rust_str(prefix + to_rust_regex(pattern))},"
            f" transform: {transformer(args[2] if len(args) > 2 else None)},"
            f' remove: {str(options.get("remove", False)).lower()},'
            f' skip_if_found: {str(options.get("skipIfAlreadyFound", True)).lower()},'
            f' skip_from_title: {str(options.get("skipFromTitle", False)).lower()},'
            f' skip_if_first: {str(options.get("skipIfFirst", False)).lower()},'
            " }),"
        )
    print("];")


main()
